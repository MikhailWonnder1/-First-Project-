#Согласно стандартам PEP-8 название класса следует начинать с заглавной буквы. В идеале название
#   должно отражать суть класса. Например:

class EmptyClass: #класс с именем EmptyClass
    pass     #оператор-заглушка pass(ничего не делает), класс EmptyClass - пустой

#Такой класс не особо полезен, поэтому сделаем другой пример. 


class Point:
    color = 'red' #атрибут класса(цвет)
    circle = 2    #атрибут класса(радиус точек)

print(Point.__dict__) # с помощью этой функции можно посмотреть атрибуты класса. 
#Переменная внутри класса называется атрибутом или свойством этого класса. 
#Соответственно все экземпляры класса Point будут иметь свойства,
#   указанные в качестве атрибутов класса Point, а изменение атрибутов этого класса
#   изменит и атрибуты экземпляров данного класса на соответствующие.
# Создадим несколько экземпляров данного класса: 

Point1 = Point() #Экземпляр класса Point со свойствами этого класса
Point2 = Point() #Экземпляр класса Point со свойствами этого класса

print(type(Point1), type(Point2), sep='\n') # Эта функция в данном случае показывает принадлежность экземпляра к классу
#функция type() возвращает тип объекта
print(isinstance(Point1, Point)) # с помощью этой функции также можно проверить принадлежность Point1/Point2 к конкретному классу Point
#Возвращает(True/False)
#isinstance(5, int) проверяет принадлежность объекта к определенному типу. В данном случае тоже будет True


